# 인접한 두 요소를 비교하여 정렬하는 가장 간단한 정렬 알고리즘.
# 알고리즘 설명
# 리스트의 첫 번째 요소부터 인접한 두 요소를 비교합니다.
# 앞의 요소가 뒤의 요소보다 크면 두 요소를 교환합니다.
# 리스트의 끝까지 이 과정을 반복합니다.
# 1~3단계를 리스트가 완전히 정렬될 때까지 반복합니다.
# 최악, 평균, 최선의 경우 모두 O(n²)

def bubble_sort(arr):
    n = len(arr)
    for i in range(n):
        # 마지막 i개의 요소는 이미 정렬되어 있으므로 제외
        for j in range(0, n - i - 1):
            if arr[j] > arr[j + 1]:
                # 요소 교환
                arr[j], arr[j + 1] = arr[j + 1], arr[j]


# 사용 예시
data = [64, 34, 25, 12, 22, 11, 90]
bubble_sort(data)
print("정렬된 배열:")
print(data)

# 정렬된 배열:
# [11, 12, 22, 25, 34, 64, 90]
